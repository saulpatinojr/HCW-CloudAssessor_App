#!/usr/bin/env python
"""Catalog gate: schema drift, learnUrl host allow-list, scoring coverage; optional docs generation.

uv run python scripts/check-catalog.py                 # validate (CI)
uv run python scripts/check-catalog.py --write-schema  # regenerate catalog/schema.json from the model
uv run python scripts/check-catalog.py --doc           # print docs/rules/catalog.md (CI checks it for drift)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
CATALOG_DIR = ROOT / "packages" / "cloud-assessor-core" / "catalog"

from cloud_assessor_core.catalog.loader import CatalogError, load_catalog, load_scoring  # noqa: E402
from cloud_assessor_core.catalog.schema import schema_matches, schema_text  # noqa: E402
from cloud_assessor_core.model import LEARN_URL_HOSTS  # noqa: E402


def write_schema() -> None:
    (CATALOG_DIR / "schema.json").write_text(schema_text(), encoding="utf-8")
    print(f"wrote {CATALOG_DIR / 'schema.json'}")


def validate() -> int:
    problems: list[str] = []
    schema_path = CATALOG_DIR / "schema.json"
    if not schema_path.is_file() or not schema_matches(schema_path.read_text(encoding="utf-8")):
        problems.append("schema.json has drifted from the pydantic model (run --write-schema)")
    try:
        catalog = load_catalog(CATALOG_DIR, check_schema=False)
    except CatalogError as exc:
        problems.append(str(exc))
        catalog = None
    if catalog is not None:
        for c in catalog.criteria:
            host = urlsplit(c.learnUrl).hostname
            if host not in LEARN_URL_HOSTS:
                problems.append(f"{c.id}: learnUrl host {host!r} not allowed")
            if c.when is not None and c.resourceTypes == ["estate"]:
                problems.append(f"{c.id}: estate criteria cannot carry a when clause")
        scoring = load_scoring(CATALOG_DIR)
        for fw, spec in scoring.frameworks.items():
            used = {c.pillar for c in catalog.criteria if c.framework == fw}
            for pillar in spec.pillars:
                if pillar not in used:
                    problems.append(f"scoring.json: {fw}/{pillar} has a weight but no criterion")
        ids = [c.id for c in catalog.criteria]
        if ids != sorted(ids):
            problems.append("criteria are not sorted by id")
        unverified = sum(1 for c in catalog.criteria if c.verify)
        print(
            f"catalog {catalog.version}: {len(catalog.criteria)} criteria, {unverified} with learnUrl marked [VERIFY]"
        )
    for p in problems:
        print(f"ERROR: {p}", file=sys.stderr)
    return 1 if problems else 0


def doc() -> str:
    catalog = load_catalog(CATALOG_DIR)
    scoring = load_scoring(CATALOG_DIR)
    lines = [
        "# Criteria catalog",
        "",
        "Generated by `scripts/check-catalog.py --doc`; do not edit by hand (CI fails on drift).",
        "",
        f"Catalog version {catalog.version}, retrieved {catalog.retrievedOn}, {len(catalog.criteria)} criteria.",
        "",
        "## Attribution",
        "",
    ]
    lines.extend(f"- {a}" for a in catalog.attribution)
    lines += ["", "## Pillar weights", "", "| Framework | Pillar | Weight |", "|---|---|---|"]
    for spec in scoring.frameworks.values():
        for pillar, w in spec.pillars.items():
            lines.append(f"| {spec.label} | {pillar} | {w:g} |")
    lines += [
        "",
        f"Severity weights: {', '.join(f'{k} {v}' for k, v in scoring.severityWeights.items())}.",
        "",
        "## Criteria",
        "",
        "| Id | Framework | Pillar | Severity | Resource types | Title | Checks | Learn | Verify |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for c in catalog.criteria:
        checks = (" any of: " if c.anyPass else "") + "; ".join(_check_text(k) for k in c.checks)
        when = ""
        if c.when:
            clause = "in " + json.dumps(c.when.in_) if c.when.in_ is not None else "= " + json.dumps(c.when.equals)
            when = f" (when `{c.when.path}` {clause})"
        types = ", ".join(f"`{t}`" for t in c.resourceTypes)
        verify = "[VERIFY]" if c.verify else "verified"
        lines.append(
            f"| {c.id} | {c.framework} | {c.pillar} | {c.severity} | {types} | {c.title} | {checks}{when} "
            f"| [{urlsplit(c.learnUrl).hostname}]({c.learnUrl}) | {verify} |"
        )
    lines += ["", "## Texts", ""]
    for c in catalog.criteria:
        lines += [
            f"### {c.id} {c.title}",
            "",
            c.text,
            "",
            f"Remediation: {c.remediation}",
            "",
            f"Attribution: {c.attribution} Retrieved {c.retrievedOn}.",
            "",
        ]
    return "\n".join(lines)


def _check_text(k) -> str:
    if k.kind == "tag-present":
        return f"tag-present {k.mode} of {', '.join(k.keys or [])}"
    if k.kind == "property-equals":
        return f"`{k.path}` == {json.dumps(k.anyOf if k.anyOf is not None else k.equals)} (missing: {k.missingIs})"
    if k.kind == "property-exists":
        return f"`{k.path}` {k.mustBe}"
    if k.kind == "sku-in":
        members = json.dumps(k.allowed if k.allowed is not None else k.disallowed)
        return f"`{k.path or 'sku.name'}` in {members} (missing: {k.missingIs})"
    if k.kind == "count-threshold":
        return f"{k.scope} {k.metric} of `{k.path}` {k.op} {k.value:g}"
    return f"{k.relation} `{k.type}` (absent: {k.absentIs})"


if __name__ == "__main__":
    if "--write-schema" in sys.argv:
        write_schema()
        sys.exit(validate())
    if "--doc" in sys.argv:
        print(doc())
        sys.exit(0)
    sys.exit(validate())
